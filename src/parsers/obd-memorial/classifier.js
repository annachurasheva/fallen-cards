/**
 * classifier.js — классификация карточки: «павшие» или остальное.
 *
 * Вариант Б (TASK-0005): классификация СТРОГО по статусу выбытия,
 * а не по полноте данных. Парсер пишет ВСЁ, что пришло из ЦАМО.
 *
 * Правила (одна ветка):
 *  1. Если `cause_of_death` содержит «убит» ИЛИ «погиб» → fallen.
 *  2. Всё остальное (пропал без вести, попал в плен, умер от ран, пустое,
 *     любой другой статус) → unclassified.
 *
 * Разбор полноты и качества данных — задача другого кода, не парсера.
 */
export function classify(data) {
  const cause = (data.cause_of_death || '').toLowerCase().trim();
  if (cause.includes('убит') || cause.includes('погиб')) {
    return 'fallen';
  }
  return 'unclassified';
}